"""Generate win32_d3d11.rin: the Win32 and D3D11 declarations rasm programs import.

rinbind keeps the declarations of one header file per run (its --filter
matches a file name), so this runs it once per header the lessons need and
concatenates the results. Every struct comes out complete with clang's field
offsets as comments, every COM interface with its *Vtbl struct, every enum with
its values, and every object-like macro as a #define.

    python gen_bindings.py            (needs rinbind.exe, from RIN_HOME or the default package)
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RIN_HOME = os.environ.get("RIN_HOME", r"C:\devel\rin-windows-x64")
RINBIND = os.path.join(RIN_HOME, "rinbind.exe")

# The wrapper every run parses, so each header sees the same macros.
WRAPPER = "win32_d3d11.h"

HEADERS = [
    # base types and Win32
    "basetsd.h", "minwindef.h", "windef.h", "winnt.h", "guiddef.h", "minwinbase.h",
    "winuser.h", "libloaderapi.h", "processthreadsapi.h", "fileapi.h", "handleapi.h",
    "memoryapi.h", "sysinfoapi.h", "profileapi.h", "synchapi.h", "debugapi.h",
    "errhandlingapi.h", "winbase.h", "unknwnbase.h",
    # D3D11, DXGI, the shader compiler
    "d3dcommon.h", "d3d11.h", "dxgicommon.h", "dxgiformat.h", "dxgitype.h", "dxgi.h",
    "d3dcompiler.h",
]


def main():
    out_path = os.path.join(HERE, "win32_d3d11.rin")
    parts = []
    for header in HEADERS:
        tmp = os.path.join(HERE, "_part.rin")
        r = subprocess.run([RINBIND, WRAPPER, tmp, "--filter", header], cwd=HERE)
        if r.returncode != 0:
            print(f"rinbind failed on {header}", file=sys.stderr)
            sys.exit(1)
        with open(tmp, encoding="utf-8") as f:
            text = f.read()
        # Everything here is a C header's: an alias is a typedef C already
        # has, so it is external like the structs and enums rinbind marks.
        text = re.sub(r"^([A-Za-z_][A-Za-z0-9_]*): alias = ", r"\1: alias[external] = ", text, flags=re.M)
        os.remove(tmp)
        print(f"{header}: {text.count(chr(10))} lines")
        parts.append(f"// ---- {header} " + "-" * max(4, 70 - len(header)) + "\n" + text)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by gen_bindings.py with rinbind. Do not edit.\n\n")
        f.write("\n".join(parts))
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
